import Anthropic from "@anthropic-ai/sdk";
import { logClaude } from "./usage";

// Вопрос внутри обычной записи.
//
// Человек наговаривает день и по дороге спрашивает: «а Исландия это остров или
// материк?». Для бота это была запись — и вопрос оставался без ответа, либо,
// что хуже, на него отвечал отклик под записью: по памяти, без проверки и тем
// же уверенным тоном, каким он выдал бы ошибку.
//
// Поэтому вопрос вылавливаем отдельно и отдаём тому, у кого есть поиск.
// Джарвиса не нужно звать по имени — если ты спросил, он отвечает.

// Отсекаем очевидное без модели: где нет вопросительного знака и нет вопросительного
// слова, звать модель незачем.
const MAYBE = /[?？]|(^|\s)(что|как|где|когда|почему|зачем|сколько|какой|какая|какие|кто|можно ли|правда ли)(\s|,)/i;

export async function findQuestion(userId: string, text: string): Promise<string | null> {
  const t = (text || "").trim();
  if (t.length < 12 || !MAYBE.test(t) || !process.env.ANTHROPIC_API_KEY) return null;
  try {
    const m = await new Anthropic({ apiKey: process.env.ANTHROPIC_API_KEY }).messages.create({
      model: "claude-haiku-4-5-20251001",
      max_tokens: 120,
      temperature: 0,
      system: `Человек надиктовал запись в личный дневник. Найди в ней ВОПРОС, на который он реально ждёт ответа со стороны — факт, справку, объяснение, совет по делу.

Верни сам вопрос одной строкой, своими словами, если он есть. Если вопроса нет — верни ровно: НЕТ.

Возвращай НЕТ, когда:
— вопрос риторический или обращён к себе: «не знаю, что с этим делать», «и зачем я только согласился», «когда это кончится»;
— человек размышляет вслух, а не спрашивает;
— вопрос про его собственную жизнь и его же записи («а сколько я потратил?») — на такое ответит другой путь;
— вопрос уже содержит ответ.

Возвращай вопрос, когда человек спрашивает о МИРЕ: факт, значение, как что-то работает, где что находится, чем отличается одно от другого.`,
      messages: [{ role: "user", content: t.slice(0, 2000) }],
    });
    logClaude(userId, "entry-question", "haiku", (m as any).usage);
    const out = m.content.filter((b) => b.type === "text").map((b: any) => b.text).join(" ").trim();
    if (!out || /^нет\b/i.test(out) || out.length < 6) return null;
    return out.slice(0, 300);
  } catch {
    return null;
  }
}
